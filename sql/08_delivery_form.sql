-- 0) The id of tbl_Delivery and tbl_fabric_info_delivered has no identity / default, so inserts would fail
--    ("null value in column id"). Make them auto-numbered, continuing after any existing id.
do $$
declare t text;
begin
  foreach t in array array['tbl_Delivery', 'tbl_fabric_info_delivered'] loop
    if exists (select 1 from information_schema.columns
               where table_schema = 'public' and table_name = t and column_name = 'id'
                 and is_identity = 'NO' and column_default is null) then
      execute format('alter table public.%I alter column id add generated by default as identity', t);
      execute format('select setval(pg_get_serial_sequence(%L, %L), coalesce((select max(id) from public.%I), 0) + 1, false)',
                     'public.' || quote_ident(t), 'id', t);
    end if;
  end loop;
end $$;

-- 1) tbl_Customer_Sync: the default alias of the customer (mirrored from charles-supabase's tbl_Customer).
--    No foreign key on purpose: a customer must never be rejected because its alias hasn't arrived yet.
alter table public."tbl_Customer_Sync" add column if not exists default_alias_id bigint;

-- The delivery form can change the default alias of a customer. That is the ONLY column the app may update here.
-- (The mirror is written by the sync from charles-supabase, which wins on the next change of that customer.)
revoke update on public."tbl_Customer_Sync" from authenticated, anon;
grant  update (default_alias_id) on public."tbl_Customer_Sync" to authenticated, anon;
drop policy if exists "default_alias_update" on public."tbl_Customer_Sync";
create policy "default_alias_update" on public."tbl_Customer_Sync" for update to authenticated, anon using (true) with check (true);

