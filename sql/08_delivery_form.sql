-- 3) "copied" goes back to false whenever a delivery is created or changed, or its delivered rolls change.
--    (Setting copied = true on its own, as the copy process does, is left alone.)
create or replace function public.delivery_reset_copied()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    new.copied := false;
  elsif (new.job_order_id, new.delivery_receipt, new.receivable_type_id, new.date_delivery, new.alias_id,
         new.shrinkage_length, new.shrinkage_width, new.acquired_density)
        is distinct from
        (old.job_order_id, old.delivery_receipt, old.receivable_type_id, old.date_delivery, old.alias_id,
         old.shrinkage_length, old.shrinkage_width, old.acquired_density) then
    new.copied := false;
  end if;
  return new;
end $$;

drop trigger if exists trg_delivery_copied on public."tbl_Delivery";
create trigger trg_delivery_copied
  before insert or update on public."tbl_Delivery"
  for each row execute function public.delivery_reset_copied();

create or replace function public.delivery_rolls_reset_copied()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  update public."tbl_Delivery" set copied = false
   where id = coalesce(new.delivery_id, old.delivery_id) and copied;
  return null;
end $$;

drop trigger if exists trg_delivery_rolls_copied on public."tbl_fabric_info_delivered";
create trigger trg_delivery_rolls_copied
  after insert or update or delete on public."tbl_fabric_info_delivered"
  for each row execute function public.delivery_rolls_reset_copied();

-- 4) Job orders that can still be delivered (no tbl_Delivery row yet), found by job ticket typed with or without dashes
create or replace function public.delivery_candidates(p_search text default '', p_limit integer default 50)
returns table (id bigint, job_ticket text, sales_id bigint, date_job_order date,
               color_id bigint, tone_id bigint, fabric_id bigint, dye_process_id bigint)
language sql
stable
set search_path = public
as $$
  select j.id, j.job_ticket, j.sales_id, j.date_job_order, j.color_id, j.tone_id, j.fabric_id, j.dye_process_id
  from public."tbl_job_order" j
  where not exists (select 1 from public."tbl_Delivery" d where d.job_order_id = j.id)
    and (btrim(coalesce(p_search, '')) = ''
         or regexp_replace(lower(j.job_ticket), '[\s-]', '', 'g')
            like '%' || regexp_replace(lower(p_search), '[%_\s-]', '', 'g') || '%')
  order by j.date_job_order desc nulls last, j.id desc
  limit least(coalesce(p_limit, 50), 200);
$$;

-- 5) Saves a delivery and its delivered rolls in ONE transaction (p_id null = new, otherwise update + replace the rolls).
--    A SMALL receipt never keeps an alias. p_rolls = [{"roll_type_id": 1, "roll_wt": 25.4}, ...]
create or replace function public.delivery_save(
  p_id                 bigint,
  p_job_order_id       bigint,
  p_delivery_receipt   bigint,
  p_receivable_type_id bigint,
  p_date_delivery      date,
  p_alias_id           bigint,
  p_shrinkage_length   smallint,
  p_shrinkage_width    smallint,
  p_acquired_density   smallint,
  p_rolls              jsonb
)
returns bigint
language plpgsql
set search_path = public
as $$
declare
  v_id    bigint;
  v_alias bigint := case when p_receivable_type_id = 2 then null else p_alias_id end;
begin
  if p_id is null then
    insert into public."tbl_Delivery"
      (job_order_id, delivery_receipt, receivable_type_id, date_delivery, alias_id, shrinkage_length, shrinkage_width, acquired_density)
    values
      (p_job_order_id, p_delivery_receipt, p_receivable_type_id, p_date_delivery, v_alias, p_shrinkage_length, p_shrinkage_width, p_acquired_density)
    returning id into v_id;
  else
    update public."tbl_Delivery"
       set delivery_receipt = p_delivery_receipt, receivable_type_id = p_receivable_type_id, date_delivery = p_date_delivery,
           alias_id = v_alias, shrinkage_length = p_shrinkage_length, shrinkage_width = p_shrinkage_width,
           acquired_density = p_acquired_density
     where id = p_id
    returning id into v_id;
    if v_id is null then raise exception 'Delivery % was not found', p_id; end if;
    delete from public."tbl_fabric_info_delivered" where delivery_id = v_id;
  end if;

  insert into public."tbl_fabric_info_delivered" (delivery_id, roll_type_id, roll_wt)
  select v_id, (r->>'roll_type_id')::bigint, (r->>'roll_wt')::double precision
  from jsonb_array_elements(coalesce(p_rolls, '[]'::jsonb)) r;

  update public."tbl_Delivery" set copied = false where id = v_id;   -- a saved or changed record is not copied yet
  return v_id;
end $$;

